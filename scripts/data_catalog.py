def agree(adjective: str, gender: str) -> str:
    """Согласует прилагательное на -ый с родом существительного: m — -ый, f — -ая, n — -ое."""
    stem = adjective[:-2]
    return {"m": adjective, "f": stem + "ая", "n": stem + "ое"}[gender]

